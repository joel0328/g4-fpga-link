#!/usr/bin/env python3
"""gen_regs.py - generate the register map files from regs/regmap.toml.

    python scripts/gen_regs.py           write every generated file
    python scripts/gen_regs.py --check   exit 1 if any generated file is stale

Outputs: rtl/fpga_regs.vh, firmware/FPGA_Link/Core/Inc/fpga_regs.h,
tools/fpga_regs.py, tools/fpga_regs.m and the README register table (between
the regmap markers). Needs Python 3.11+ (tomllib); no other packages.
"""
import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "regs" / "regmap.toml"
VH = ROOT / "rtl" / "fpga_regs.vh"
H = ROOT / "firmware" / "FPGA_Link" / "Core" / "Inc" / "fpga_regs.h"
PY = ROOT / "tools" / "fpga_regs.py"
M = ROOT / "tools" / "fpga_regs.m"
README = ROOT / "README.md"
BEGIN = "<!-- regmap:begin (generated by scripts/gen_regs.py from regs/regmap.toml) -->"
END = "<!-- regmap:end -->"
ACCESS = {"RO", "RW", "W", "RW1C"}
NOTICE = "Generated by scripts/gen_regs.py from regs/regmap.toml. Do not edit."


class MapError(Exception):
    pass


def parse_bits(text):
    """'5' -> (5, 5); '15:0' -> (15, 0)."""
    parts = str(text).split(":")
    msb = int(parts[0])
    lsb = int(parts[-1])
    if len(parts) > 2 or not 0 <= lsb <= msb <= 31:
        raise MapError(f"bad bit range {text!r}")
    return msb, lsb


def load(path=SRC):
    with open(path, "rb") as f:
        doc = tomllib.load(f)
    mp = doc["map"]
    mp["const"] = doc.get("const", {})
    regs = doc["reg"]
    by_name = {}
    used = {}
    for r in regs:
        name = r["name"]
        if name in by_name:
            raise MapError(f"duplicate register {name}")
        if r["access"] not in ACCESS:
            raise MapError(f"{name}: access {r['access']!r} not one of {sorted(ACCESS)}")
        r.setdefault("words", 1)
        r["desc"] = r["desc"].format(**mp)
        for a in range(r["addr"], r["addr"] + r["words"]):
            if not 0 <= a < 0x80:
                raise MapError(f"{name}: address 0x{a:02X} out of range")
            if a == mp["burst_addr"]:
                raise MapError(f"{name}: 0x{a:02X} is the burst escape")
            if a in used:
                raise MapError(f"{name}: address 0x{a:02X} already used by {used[a]}")
            used[a] = name
        prefix = r.get("field_prefix", name)
        mask = 0
        for fld in r.get("fields", []):
            fld["msb"], fld["lsb"] = parse_bits(fld["bits"])
            stem = f"{prefix}_{fld['name']}" if prefix else fld["name"]
            fld["stem"] = stem
            fld["c"] = fld.get("c", "FPGA_" + stem)
            bits = ((1 << (fld["msb"] - fld["lsb"] + 1)) - 1) << fld["lsb"]
            if mask & bits:
                raise MapError(f"{name}.{fld['name']} overlaps another field")
            mask |= bits
            fld["mask"] = bits
        by_name[name] = r
    for r in regs:
        if "fields_from" in r and r["fields_from"] not in by_name:
            raise MapError(f"{r['name']}: fields_from {r['fields_from']!r} unknown")
    for reg, key in (("ID", "id"), ("VERSION", "version")):
        if by_name.get(reg, {}).get("reset") != mp[key]:
            raise MapError(f"{reg}.reset must equal [map].{key}")
    cnames = [f["c"] for r in regs for f in r.get("fields", [])]
    if len(cnames) != len(set(cnames)):
        raise MapError("duplicate field C names")
    return mp, regs


def addr_range(r):
    if r["words"] == 1:
        return f"0x{r['addr']:02X}"
    return f"0x{r['addr']:02X}-0x{r['addr'] + r['words'] - 1:02X}"


def field_value_c(f):
    if f["msb"] == f["lsb"]:
        return f"(1u << {f['lsb']})"
    width_mask = (1 << (f["msb"] - f["lsb"] + 1)) - 1
    if f["lsb"] == 0:
        return f"0x{width_mask:08X}u"
    return f"(0x{width_mask:X}u << {f['lsb']})"


# ---------------------------------------------------------------- Verilog
def gen_vh(mp, regs):
    out = [
        f"// fpga_regs.vh - register map version {mp['version']}. {NOTICE}",
        "// `include inside a module body (localparams only, so no include guard).",
        "",
        f"localparam [31:0] MAP_VERSION    = 32'h{mp['version']:08X};",
        f"localparam [31:0] MAP_ID         = 32'h{mp['id']:08X};",
        f"localparam [31:0] MAP_UNMAPPED   = 32'h{mp['unmapped']:08X};",
        f"localparam [6:0]  MAP_BURST_ADDR = 7'h{mp['burst_addr']:02X};",
        f"localparam integer MAP_BURST_MAX = {mp['burst_max']};",
    ]
    for k, v in mp["const"].items():
        out.append(f"localparam [31:0] {k} = 32'h{v:08X};")
    out += ["", "// Register addresses"]
    w = max(len(r["name"]) for r in regs) + 4
    for r in regs:
        out.append(f"localparam [6:0] {('REG_' + r['name']).ljust(w)} = 7'h{r['addr']:02X};"
                   f"  // {r['access']:<4} {addr_range(r)}")
        if r["words"] > 1:
            out.append(f"localparam integer {('REG_' + r['name'] + '_WORDS').ljust(w - 2)} = {r['words']};")
    out.append("")
    out.append("// Fields: single bits are bit numbers; wider fields have _LSB, _MSB and _W")
    for r in regs:
        fields = r.get("fields", [])
        if not fields:
            continue
        out.append(f"// {r['name']}")
        for f in fields:
            if f["msb"] == f["lsb"]:
                out.append(f"localparam integer {f['stem']} = {f['lsb']};")
            else:
                out.append(f"localparam integer {f['stem']}_LSB = {f['lsb']};")
                out.append(f"localparam integer {f['stem']}_MSB = {f['msb']};")
                out.append(f"localparam integer {f['stem']}_W = {f['msb'] - f['lsb'] + 1};")
        out.append(f"localparam integer {r['name']}_W = {max(f['msb'] for f in fields) + 1};"
                   "  // bits up to the highest field")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------- C
def gen_h(mp, regs):
    out = [
        "/*",
        f" * fpga_regs.h - register map version {mp['version']} for the Basys 3 link bitstream.",
        f" * {NOTICE}",
        " */",
        "#ifndef FPGA_REGS_H",
        "#define FPGA_REGS_H",
        "",
    ]
    w = max(len(r["name"]) for r in regs) + 9
    for r in regs:
        out.append(f"#define {('FPGA_REG_' + r['name']).ljust(w)} 0x{r['addr']:02X}u"
                   f"  /* {r['access']:<4} {c_comment(r['desc'])} */")
        if r["words"] > 1:
            out.append(f"#define {('FPGA_' + r['name'] + '_WORDS').ljust(w)} {r['words']}u")
    out += [
        "",
        f"#define FPGA_ID_VALUE        0x{mp['id']:08X}u",
        f"#define FPGA_MAP_VERSION     {mp['version']}u",
        f"#define FPGA_UNMAPPED_VALUE  0x{mp['unmapped']:08X}u",
        "",
        f"/* Burst frames: header address 0x{mp['burst_addr']:02X} is the escape, never a register */",
        f"#define FPGA_BURST_ADDR      0x{mp['burst_addr']:02X}u",
        f"#define FPGA_BURST_MAX       {mp['burst_max']}u",
    ]
    if mp["const"]:
        out += [""] + [f"#define {('FPGA_' + k).ljust(20)} {c_const(v)}" for k, v in mp["const"].items()]
    for r in regs:
        fields = r.get("fields", [])
        if not fields:
            continue
        shared = [o["name"] for o in regs if o.get("fields_from") == r["name"]]
        out += ["", f"/* {' / '.join([r['name']] + shared)} fields */"]
        cw = max(20, max(len(f["c"]) for f in fields))
        for f in fields:
            out.append(f"#define {f['c'].ljust(cw)} {field_value_c(f)}")
    out += [
        "",
        f"/* LOOP_TICK helpers (FPGA system clock is {mp['clk_hz'] // 1_000_000} MHz) */",
        f"#define FPGA_CLK_HZ          {mp['clk_hz']}u",
        "#define FPGA_TICK_DIV_FOR_HZ(hz) (FPGA_CLK_HZ / (hz))",
        "",
        "#endif /* FPGA_REGS_H */",
    ]
    return "\n".join(out) + "\n"


def c_const(v):
    return f"0x{v:08X}u" if v > 0xFFFF else f"{v}u"


def c_comment(text):
    return text.replace("*/", "* /").replace("µs", "us").replace("–", "-")


# ----------------------------------------------------------------- Python
def gen_py(mp, regs):
    out = [
        f'"""fpga_regs.py - register map version {mp["version"]}. {NOTICE}"""',
        "",
        f"MAP_VERSION = {mp['version']}",
        f"ID_VALUE = 0x{mp['id']:08X}",
        f"UNMAPPED_VALUE = 0x{mp['unmapped']:08X}",
        f"BURST_ADDR = 0x{mp['burst_addr']:02X}",
        f"BURST_MAX = {mp['burst_max']}",
        f"CLK_HZ = {mp['clk_hz']}",
    ]
    out += [f"{k} = 0x{v:08X}" if v > 0xFFFF else f"{k} = {v}" for k, v in mp["const"].items()]
    out += ["", "# Register addresses"]
    for r in regs:
        out.append(f"REG_{r['name']} = 0x{r['addr']:02X}")
        if r["words"] > 1:
            out.append(f"{r['name']}_WORDS = {r['words']}")
    out += ["", "# Fields (in-place masks)"]
    for r in regs:
        for f in r.get("fields", []):
            out.append(f"{f['c'].removeprefix('FPGA_')} = 0x{f['mask']:08X}")
    out += ["", "# name: (address, words, access, description)", "REGS = {"]
    for r in regs:
        out.append(f"    {r['name']!r}: (0x{r['addr']:02X}, {r['words']}, {r['access']!r}, {r['desc']!r}),")
    out.append("}")
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------- MATLAB
def gen_m(mp, regs):
    out = [
        "function r = fpga_regs()",
        f"%FPGA_REGS Register map version {mp['version']} for the G4 <-> FPGA link.",
        "%   r = fpga_regs() returns a struct: r.REG.<name> addresses, r.FIELD.<name>",
        "%   in-place masks (use with bitand), and the map constants.",
        f"%   {NOTICE}",
        "",
        f"r.MAP_VERSION = {mp['version']};",
        f"r.ID_VALUE = {mp['id']};  % 0x{mp['id']:08X}",
        f"r.UNMAPPED_VALUE = {mp['unmapped']};  % 0x{mp['unmapped']:08X}",
        f"r.BURST_ADDR = {mp['burst_addr']};  % 0x{mp['burst_addr']:02X}",
        f"r.BURST_MAX = {mp['burst_max']};",
        f"r.CLK_HZ = {mp['clk_hz']};",
    ]
    out += [f"r.{k} = {v};" + (f"  % 0x{v:08X}" if v > 0xFFFF else "") for k, v in mp["const"].items()]
    out.append("")
    for r in regs:
        out.append(f"r.REG.{r['name']} = {r['addr']};  % 0x{r['addr']:02X} {r['access']}")
        if r["words"] > 1:
            out.append(f"r.WORDS.{r['name']} = {r['words']};")
    out.append("")
    for r in regs:
        for f in r.get("fields", []):
            out.append(f"r.FIELD.{f['c'].removeprefix('FPGA_')} = {f['mask']};  % 0x{f['mask']:08X}")
    out.append("end")
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------- README
def gen_table(mp, regs):
    out = [
        BEGIN,
        f"## Register map (version {mp['version']})",
        "",
        "| Addr | Name | Access | Description |",
        "|---|---|---|---|",
    ]
    for r in regs:
        a = addr_range(r).replace("-", "–")
        out.append(f"| {a} | {r['name']} | {r['access']} | {r['desc']} |")
    out.append(f"| 0x{mp['burst_addr']:02X} | — | — | Reserved: the burst escape in the frame header, never a register |")
    out.append(END)
    return "\n".join(out)


def splice_readme(text, table):
    try:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
    except ValueError:
        raise MapError("README.md has no regmap markers")
    return head + table + tail


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report stale files")
    args = ap.parse_args()
    try:
        mp, regs = load()
        outputs = {VH: gen_vh(mp, regs), H: gen_h(mp, regs),
                   PY: gen_py(mp, regs), M: gen_m(mp, regs)}
        readme = read(README)
        if readme is None:
            raise MapError("README.md missing")
        outputs[README] = splice_readme(readme, gen_table(mp, regs))
    except (MapError, KeyError) as e:
        print(f"gen_regs: {e}", file=sys.stderr)
        return 2
    stale = [p for p, text in outputs.items() if read(p) != text]
    if args.check:
        for p in stale:
            print(f"gen_regs: stale {p.relative_to(ROOT).as_posix()} (run make regs)", file=sys.stderr)
        if not stale:
            print(f"gen_regs: map version {mp['version']}, all generated files up to date")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(outputs[p])
        print(f"gen_regs: wrote {p.relative_to(ROOT).as_posix()}")
    if not stale:
        print("gen_regs: nothing to do")
    return 0


if __name__ == "__main__":
    sys.exit(main())
